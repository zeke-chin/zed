"""Writes the pruned .proto files under crates/fork_windsurf/proto from the
descriptor set extracted in stage 2 (fork/spike/proto-out/descriptor_set.pb).

usage (from the repository root, with a python that has `protobuf` installed):
  python crates/fork_windsurf/proto/prune.py fork/spike/proto-out/descriptor_set.pb crates/fork_windsurf/proto crates/fork_windsurf/proto/prune_spec.txt

prune_spec.txt: `root .pkg.Message` adds a message and everything it uses;
`keep .pkg.Message field ...` keeps only the listed fields of that message.
"""
import os, sys
from google.protobuf import descriptor_pb2 as d
fds = d.FileDescriptorSet(); fds.ParseFromString(open(sys.argv[1],'rb').read())
out = sys.argv[2]
roots=[]; keep={}
for line in open(sys.argv[3]):
    line=line.split('#')[0].split()
    if not line: continue
    if line[0]=='root': roots.append(line[1])
    elif line[0]=='keep': keep[line[1]]=set(line[2:])
msgs={}; enums={}; owner={}
def walk(prefix,m,f):
    full=prefix+"."+m.name; msgs[full]=m; owner[full]=f
    for n in m.nested_type: walk(full,n,f)
    for e in m.enum_type: enums[full+"."+e.name]=e; owner[full+"."+e.name]=f
for f in fds.file:
    p="."+f.package if f.package else ""
    for m in f.message_type: walk(p,m,f)
    for e in f.enum_type: enums[p+"."+e.name]=e; owner[p+"."+e.name]=f
def kept_fields(name):
    m=msgs[name]
    if name in keep:
        missing = keep[name]-{x.name for x in m.field}
        assert not missing, (name, missing)
        return [x for x in m.field if x.name in keep[name]]
    return list(m.field)
seen=set(); stack=list(roots)
while stack:
    n=stack.pop()
    if n in seen: continue
    assert n in msgs or n in enums, n
    seen.add(n)
    if n in msgs:
        for fl in kept_fields(n):
            if fl.type_name: stack.append(fl.type_name)
        # parent messages must exist for nested types
    parts=n.split(".")
for n in list(seen):
    # ensure parents of nested types are emitted
    p=n.rsplit(".",1)[0]
    while p in msgs:
        if p not in seen:
            # Only needed as a namespace for a nested type: emit it without fields.
            seen.add(p); keep[p]=set()
        p=p.rsplit(".",1)[0]
SCALAR={1:"double",2:"float",3:"int64",4:"uint64",5:"int32",6:"fixed64",7:"fixed32",8:"bool",9:"string",12:"bytes",13:"uint32",15:"sfixed32",16:"sfixed64",17:"sint32",18:"sint64"}
def tname(fl):
    return fl.type_name if fl.type_name else SCALAR[fl.type]
def emit_enum(e,ind):
    s=[f"{ind}enum {e.name} {{"]
    for v in e.value: s.append(f"{ind}  {v.name} = {v.number};")
    s.append(f"{ind}}}"); return s
def emit_msg(full,ind,refs):
    m=msgs[full]; s=[f"{ind}message {m.name} {{"]
    for e in m.enum_type: s+=emit_enum(e,ind+"  ")
    for n in m.nested_type:
        nf=full+"."+n.name
        if n.options.map_entry: continue
        if nf in seen: s+=emit_msg(nf,ind+"  ",refs)
    fields=kept_fields(full)
    oneofs={}
    def line(fl):
        if fl.type_name: refs.add(fl.type_name)
        t=tname(fl)
        if fl.type_name and fl.type_name in msgs and msgs[fl.type_name].options.map_entry:
            me=msgs[fl.type_name]; k=me.field[0]; v=me.field[1]
            if v.type_name: refs.add(v.type_name)
            return f"map<{tname(k)}, {tname(v)}> {fl.name} = {fl.number};"
        lab="repeated " if fl.label==3 else ("optional " if fl.proto3_optional else "")
        return f"{lab}{t} {fl.name} = {fl.number};"
    for fl in fields:
        if fl.HasField("oneof_index") and not fl.proto3_optional:
            oneofs.setdefault(fl.oneof_index,[]).append(fl)
        else:
            s.append(ind+"  "+line(fl))
    for idx, fls in oneofs.items():
        s.append(f"{ind}  oneof {m.oneof_decl[idx].name} {{")
        for fl in fls: s.append(ind+"    "+line(fl))
        s.append(f"{ind}  }}")
    s.append(f"{ind}}}"); return s
byfile={}
for n in seen:
    p=n.rsplit(".",1)[0]
    if p in msgs: continue  # nested
    byfile.setdefault(owner[n].name,[]).append(n)
written=[]
for fname, names in sorted(byfile.items()):
    if fname.startswith("google/"): continue
    f=[x for x in fds.file if x.name==fname][0]
    order={}
    for i,m in enumerate(f.message_type): order["."+f.package+"."+m.name]=i
    for i,e in enumerate(f.enum_type): order["."+f.package+"."+e.name]=-1000+i
    names.sort(key=lambda n: order[n])
    refs=set(); body=[]
    for n in names:
        body+= emit_enum(enums[n],"") if n in enums else emit_msg(n,"",refs)
        body.append("")
    imports=sorted({owner[r].name for r in refs if owner[r].name!=fname})
    hdr=["// Pruned from fork/spike/proto-out (Windsurf language server 1.48.2, build fcf7ba39).",
         "// Generated by crates/fork_windsurf/proto/prune.py from prune_spec.txt; regenerate instead of editing by hand.",
         'syntax = "proto3";',"",f"package {f.package};",""]
    hdr+= [f'import "{i}";' for i in imports]
    if imports: hdr.append("")
    path=os.path.join(out,fname); os.makedirs(os.path.dirname(path),exist_ok=True)
    open(path,"w").write("\n".join(hdr+body).rstrip()+"\n")
    written.append((fname,len(names)))
for w in written: print(*w)
print("types", len(seen))
